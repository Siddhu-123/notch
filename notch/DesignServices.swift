import Foundation
import AppKit
import Combine
import SwiftUI

// MARK: - Clipboard Store

public struct ClipboardEntry: Codable, Identifiable, Equatable {
    public let id: UUID
    public let text: String
    public let createdAt: Date
    public var isPinned: Bool
    
    public var title: String {
        for line in text.components(separatedBy: .newlines) {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                return trimmed.count > 50 ? String(trimmed.prefix(50)) + "..." : trimmed
            }
        }
        return ""
    }
    
    public init(id: UUID = UUID(), text: String, createdAt: Date = Date(), isPinned: Bool = false) {
        self.id = id
        self.text = text
        self.createdAt = createdAt
        self.isPinned = isPinned
    }
}

@MainActor
public final class ClipboardStore: ObservableObject {
    public static let shared = ClipboardStore()
    
    @Published public private(set) var history: [ClipboardEntry] = []
    @Published public private(set) var monitoringEnabled = false
    
    private let storageURL: URL
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let disableTimers: Bool
    private let timerScheduler: (TimeInterval, @escaping () -> Void) -> Timer
    private let defaultsMonitoringKey = "clipboard.monitoringEnabled"
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    
    private let historyLimit = 100
    private let pinLimit = 50
    private let maxTextSize = 100_000
    
    public init(storageDirectory: URL? = nil, pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard, disableTimers: Bool = false, timerScheduler: ((TimeInterval, @escaping () -> Void) -> Timer)? = nil) {
        let dir: URL
        if let storageDirectory = storageDirectory {
            dir = storageDirectory
        } else {
            let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
            dir = appSupport.appendingPathComponent("Notch")
        }
        if !FileManager.default.fileExists(atPath: dir.path) {
            try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        }
        self.storageURL = dir.appendingPathComponent("clipboard.json")
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.disableTimers = disableTimers
        self.timerScheduler = timerScheduler ?? { interval, tick in
            Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { _ in tick() }
        }
        self.lastChangeCount = pasteboard.changeCount
        self.monitoringEnabled = defaults.object(forKey: defaultsMonitoringKey) as? Bool ?? false
        load()
        if monitoringEnabled {
            startTimer()
        }
    }
    
    deinit {
        timer?.invalidate()
        timer = nil
    }
    
    public func setMonitoringEnabled(_ enabled: Bool) {
        defaults.set(enabled, forKey: defaultsMonitoringKey)
        guard monitoringEnabled != enabled else { return }
        monitoringEnabled = enabled
        if enabled {
            lastChangeCount = pasteboard.changeCount
            startTimer()
        } else {
            stopTimer()
        }
    }
    
    private func startTimer() {
        stopTimer()
        guard !disableTimers else { return }
        timer = timerScheduler(0.5) { [weak self] in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
    }
    
    public func stopMonitoringLifecycle() {
        stopTimer()
    }
    
    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }
    
    public func checkPasteboard() {
        guard monitoringEnabled else { return }
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount
        captureCurrent()
    }
    
    public func captureCurrent() {
        guard let types = pasteboard.types else { return }
        let concealedTypes = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.apple.uikit.pasteboard.source.transient"
        ]
        if types.contains(where: { concealedTypes.contains($0.rawValue) }) {
            return
        }
        
        let currentCount = pasteboard.changeCount
        if let own = ownChangeCount, own == currentCount {
            return
        }
        
        guard let text = pasteboard.string(forType: .string) else { return }
        addSnippet(text: text)
    }
    
    public func addSnippet(text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        guard text.utf8.count <= maxTextSize else { return }
        
        var existingIndex: Int?
        var existingPinned = false
        var existingId = UUID()
        
        if let idx = history.firstIndex(where: { $0.text == text }) {
            existingIndex = idx
            existingPinned = history[idx].isPinned
            existingId = history[idx].id
        }
        
        let newEntry = ClipboardEntry(id: existingId, text: text, createdAt: Date(), isPinned: existingPinned)
        
        if let idx = existingIndex {
            history.remove(at: idx)
        }
        history.insert(newEntry, at: 0)
        
        enforceBounds()
        save()
    }
    
    public func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        let count = pasteboard.changeCount
        ownChangeCount = count
        lastChangeCount = count
    }
    
    public func togglePin(_ id: UUID) {
        guard let idx = history.firstIndex(where: { $0.id == id }) else { return }
        if !history[idx].isPinned {
            let pinnedCount = history.filter({ $0.isPinned }).count
            guard pinnedCount < pinLimit else { return }
        }
        history[idx].isPinned.toggle()
        enforceBounds()
        save()
    }
    
    public func remove(_ id: UUID) {
        history.removeAll(where: { $0.id == id })
        save()
    }
    
    public func clearHistory() {
        history = history.filter { $0.isPinned }
        save()
    }
    
    private static func isNewer(_ a: ClipboardEntry, _ b: ClipboardEntry) -> Bool {
        if a.createdAt != b.createdAt { return a.createdAt > b.createdAt }
        if a.text != b.text { return a.text < b.text }
        return a.id.uuidString < b.id.uuidString
    }

    /// Normalizes `history`: unique non-empty texts (newest wins), unique ids,
    /// at most `pinLimit` pinned and `historyLimit` total. Returns true if anything changed.
    @discardableResult
    private func enforceBounds() -> Bool {
        let original = history
        var seenText = Set<String>()
        var seenIds = Set<UUID>()
        var pinnedCount = 0
        var valid: [ClipboardEntry] = []

        for var entry in history.sorted(by: Self.isNewer) {
            guard !entry.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  entry.text.utf8.count <= maxTextSize,
                  seenText.insert(entry.text).inserted else { continue }
            if !seenIds.insert(entry.id).inserted {
                entry = ClipboardEntry(id: UUID(), text: entry.text, createdAt: entry.createdAt, isPinned: entry.isPinned)
                seenIds.insert(entry.id)
            }
            if entry.isPinned {
                if pinnedCount < pinLimit { pinnedCount += 1 } else { entry.isPinned = false }
            }
            valid.append(entry)
        }

        // Keep every pin, then fill the remainder with the newest unpinned entries.
        var unpinnedBudget = max(0, historyLimit - pinnedCount)
        history = valid.filter { entry in
            if entry.isPinned { return true }
            guard unpinnedBudget > 0 else { return false }
            unpinnedBudget -= 1
            return true
        }
        return history != original
    }

    private struct Lossy<T: Decodable>: Decodable {
        let value: T?
        init(from decoder: Decoder) throws { value = try? T(from: decoder) }
    }

    private struct RawEntry: Decodable {
        let id: String?
        let text: String?
        let createdAt: Date?
        let isPinned: Bool?

        enum CodingKeys: String, CodingKey { case id, text, createdAt, isPinned }

        init(from decoder: Decoder) throws {
            let c = try decoder.container(keyedBy: CodingKeys.self)
            id = try? c.decode(String.self, forKey: .id)
            text = try? c.decode(String.self, forKey: .text)
            createdAt = try? c.decode(Date.self, forKey: .createdAt)
            isPinned = try? c.decode(Bool.self, forKey: .isPinned)
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: storageURL),
              let raw = try? JSONDecoder().decode([Lossy<RawEntry>].self, from: data) else { return }
        var malformed = false
        history = raw.compactMap { item -> ClipboardEntry? in
            guard let r = item.value, let text = r.text else { malformed = true; return nil }
            let id = r.id.flatMap { UUID(uuidString: $0) }
            if id == nil || r.createdAt == nil || r.isPinned == nil { malformed = true }
            return ClipboardEntry(id: id ?? UUID(), text: text, createdAt: r.createdAt ?? .distantPast, isPinned: r.isPinned ?? false)
        }
        let changed = enforceBounds()
        if malformed || changed { save() }
    }
    
    private func save() {
        guard let data = try? JSONEncoder().encode(history) else { return }
        do {
            try data.write(to: storageURL, options: [.atomic, .completeFileProtection])
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storageURL.path)
        } catch {
            print("Failed to save clipboard: \(error)")
        }
    }
}

// MARK: - Focus Timer Store

@MainActor
public final class FocusTimerStore: ObservableObject {
    public static let shared = FocusTimerStore()
    public static let maxAllowedDuration: TimeInterval = 525600 * 60 // 1 year in seconds
    
    @Published public private(set) var isRunning = false
    @Published public private(set) var isFinished = false
    @Published public private(set) var remainingSeconds: TimeInterval = 0
    @Published public private(set) var durationSeconds: TimeInterval = 0
    @Published public private(set) var progress: Double = 0
    @Published public private(set) var formattedRemaining: String = "00:00"
    
    private let defaults: UserDefaults
    private var timer: Timer?
    private var deadline: Date?
    private let dateProvider: () -> Date
    private let disableTimers: Bool
    
    public init(defaults: UserDefaults = .standard, disableTimers: Bool = false, dateProvider: @escaping () -> Date = { Date() }) {
        self.defaults = defaults
        self.disableTimers = disableTimers
        self.dateProvider = dateProvider
        restore()
    }
    
    deinit {
        timer?.invalidate()
        timer = nil
    }
    
    public func start(minutes: Int) {
        let maxMinutes = Int(Self.maxAllowedDuration / 60)
        let clampedMinutes: Int
        if minutes < 1 {
            clampedMinutes = 1
        } else if minutes > maxMinutes {
            clampedMinutes = maxMinutes
        } else {
            clampedMinutes = minutes
        }
        let secs = TimeInterval(clampedMinutes) * 60
        durationSeconds = secs
        remainingSeconds = secs
        deadline = dateProvider().addingTimeInterval(secs)
        isRunning = true
        isFinished = false
        updateProgress()
        save()
        scheduleTimer()
    }
    
    public func pause() {
        guard isRunning else { return }
        isRunning = false
        if let dl = deadline {
            let diff = dl.timeIntervalSince(dateProvider())
            if diff <= 0 {
                remainingSeconds = 0
                isFinished = true
            } else {
                remainingSeconds = min(diff, durationSeconds)
            }
        }
        deadline = nil
        timer?.invalidate()
        timer = nil
        updateProgress()
        save()
    }
    
    public func resume() {
        guard !isRunning, remainingSeconds > 0 else { return }
        isRunning = true
        deadline = dateProvider().addingTimeInterval(remainingSeconds)
        save()
        scheduleTimer()
    }
    
    public func reset() {
        timer?.invalidate()
        timer = nil
        isRunning = false
        isFinished = false
        remainingSeconds = 0
        durationSeconds = 0
        deadline = nil
        updateProgress()
        save()
    }
    
    public func tick(now: Date) {
        guard isRunning, let dl = deadline else { return }
        let diff = dl.timeIntervalSince(now)
        if diff <= 0 {
            remainingSeconds = 0
            isRunning = false
            isFinished = true
            timer?.invalidate()
            timer = nil
            deadline = nil
        } else {
            remainingSeconds = min(diff, durationSeconds)
        }
        updateProgress()
        save()
    }
    
    private func updateProgress() {
        if durationSeconds > 0 {
            progress = max(0, min(1, 1 - (remainingSeconds / durationSeconds)))
        } else {
            progress = 0
        }
        
        let capped = max(0, min(remainingSeconds, Self.maxAllowedDuration))
        let rounded = capped.rounded(.up)
        let total = (rounded.isFinite && rounded <= Double(Int.max)) ? Int(rounded) : 0
        let mins = total / 60
        let secs = total % 60
        formattedRemaining = String(format: "%02d:%02d", mins, secs)
    }
    
    private func scheduleTimer() {
        timer?.invalidate()
        guard !disableTimers else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                guard let self = self else { return }
                self.tick(now: self.dateProvider())
            }
        }
    }
    
    private func restore() {
        var rawDuration = defaults.double(forKey: "focus.durationSeconds")
        var rawRemaining = defaults.double(forKey: "focus.remainingSeconds")
        let rawIsRunning = defaults.bool(forKey: "focus.isRunning")
        let dlTime = defaults.double(forKey: "focus.deadline")
        
        if !rawDuration.isFinite || rawDuration < 0 { rawDuration = 0 }
        if rawDuration > Self.maxAllowedDuration { rawDuration = Self.maxAllowedDuration }
        
        if !rawRemaining.isFinite || rawRemaining < 0 { rawRemaining = 0 }
        if rawRemaining > rawDuration { rawRemaining = rawDuration }
        
        // Zero duration is always idle
        if rawDuration == 0 {
            rawRemaining = 0
            deadline = nil
            durationSeconds = 0
            remainingSeconds = 0
            isRunning = false
            isFinished = false
            updateProgress()
            save()
            return
        }
        
        durationSeconds = rawDuration
        remainingSeconds = rawRemaining
        isRunning = rawIsRunning
        isFinished = false
        
        let now = dateProvider()
        
        if isRunning, dlTime.isFinite, dlTime > 0 {
            let dlDate = Date(timeIntervalSince1970: dlTime)
            let diff = dlDate.timeIntervalSince(now)
            if diff <= 0 {
                remainingSeconds = 0
                isRunning = false
                isFinished = true
                deadline = nil
            } else {
                remainingSeconds = min(diff, durationSeconds)
                isRunning = remainingSeconds > 0
                isFinished = false
                deadline = isRunning ? now.addingTimeInterval(remainingSeconds) : nil
            }
        } else if isRunning, remainingSeconds > 0 {
            deadline = now.addingTimeInterval(remainingSeconds)
            isFinished = false
        } else {
            isRunning = false
            isFinished = remainingSeconds <= 0
            deadline = nil
        }

        updateProgress()
        if isRunning { scheduleTimer() }
        save()
    }
    
    private func save() {
        defaults.set(durationSeconds, forKey: "focus.durationSeconds")
        defaults.set(remainingSeconds, forKey: "focus.remainingSeconds")
        defaults.set(isRunning, forKey: "focus.isRunning")
        defaults.set(isFinished, forKey: "focus.isFinished")
        if let dl = deadline {
            defaults.set(dl.timeIntervalSince1970, forKey: "focus.deadline")
        } else {
            defaults.removeObject(forKey: "focus.deadline")
        }
    }
}

// MARK: - Folder Browser Store

public protocol SecurityScopedResourceManaging {
    func startAccessing(url: URL) -> Bool
    func stopAccessing(url: URL)
    func bookmarkData(for url: URL) throws -> Data
    func resolveBookmarkData(_ data: Data, isStale: inout Bool) throws -> URL
}

public struct DefaultSecurityScopedResourceManager: SecurityScopedResourceManaging {
    public init() {}
    public func startAccessing(url: URL) -> Bool {
        url.startAccessingSecurityScopedResource()
    }
    public func stopAccessing(url: URL) {
        url.stopAccessingSecurityScopedResource()
    }
    public func bookmarkData(for url: URL) throws -> Data {
        try url.bookmarkData(options: .withSecurityScope, includingResourceValuesForKeys: nil, relativeTo: nil)
    }
    public func resolveBookmarkData(_ data: Data, isStale: inout Bool) throws -> URL {
        try URL(resolvingBookmarkData: data, options: .withSecurityScope, relativeTo: nil, bookmarkDataIsStale: &isStale)
    }
}

public struct FileNode: Identifiable, Equatable {
    public let id: URL
    public let name: String
    public let isDirectory: Bool
    public let modificationDate: Date
    
    public init(url: URL, isDirectory: Bool, modificationDate: Date) {
        self.id = url
        self.name = url.lastPathComponent
        self.isDirectory = isDirectory
        self.modificationDate = modificationDate
    }
}

public struct BookmarkedFolder: Identifiable, Codable, Equatable {
    public var id: UUID
    public var bookmarkData: Data
    // Resolved once by the store, never during SwiftUI rendering.
    public var url: URL? = nil
    private enum CodingKeys: String, CodingKey { case id, bookmarkData }

    public init(id: UUID = UUID(), bookmarkData: Data, url: URL? = nil) {
        self.id = id
        self.bookmarkData = bookmarkData
        self.url = url
    }
}

@MainActor
public final class FolderBrowserStore: ObservableObject {
    public static let shared = FolderBrowserStore()
    
    @Published public private(set) var folders: [BookmarkedFolder] = []
    @Published public private(set) var selectedFolder: URL?
    @Published public private(set) var visibleChildren: [FileNode] = []
    @Published public var lastError: String?
    
    private let defaults: UserDefaults
    private let defaultsKey = "folderBrowser.folders"
    private let selectionKey = "folderBrowser.selectedFolderID"
    private var accessedURLs: [URL] = []
    private let scopeManager: SecurityScopedResourceManaging
    private var bookmarkRenewalErrors: [UUID: String] = [:]
    private var folderReadErrors: [UUID: String] = [:]
    
    public init(defaults: UserDefaults = .standard, scopeManager: SecurityScopedResourceManaging = DefaultSecurityScopedResourceManager()) {
        self.defaults = defaults
        self.scopeManager = scopeManager
        loadFolders()
    }
    
    deinit {
        for url in accessedURLs {
            scopeManager.stopAccessing(url: url)
        }
        accessedURLs.removeAll()
    }
    
    public func chooseFolder() {
        let panel = NSOpenPanel()
        panel.canChooseFiles = false
        panel.canChooseDirectories = true
        panel.allowsMultipleSelection = false
        panel.prompt = "Select Folder"
        NSApp.activate(ignoringOtherApps: true)
        
        if panel.runModal() == .OK, let url = panel.url {
            addFolder(url: url)
        }
    }
    
    public func addFolder(url: URL) {
        let resolvedURL = url.standardizedFileURL.resolvingSymlinksInPath()
        if let existing = folders.first(where: {
            $0.url?.standardizedFileURL.resolvingSymlinksInPath() == resolvedURL
        }), let targetURL = existing.url {
            selectFolder(targetURL)
            return
        }

        do {
            let data = try scopeManager.bookmarkData(for: url)
            let folder = BookmarkedFolder(bookmarkData: data, url: url)
            folders.append(folder)
            saveFolders()
            selectFolder(url)
        } catch {
            lastError = "Failed to bookmark folder: \(error.localizedDescription)"
        }
    }
    
    public func removeFolder(_ id: UUID) {
        guard let index = folders.firstIndex(where: { $0.id == id }) else { return }
        let removedURL = folders[index].url?.standardizedFileURL.resolvingSymlinksInPath()
        let removedSelection = defaults.string(forKey: selectionKey) == id.uuidString
        bookmarkRenewalErrors.removeValue(forKey: id)
        folderReadErrors.removeValue(forKey: id)
        folders.remove(at: index)
        saveFolders()
        if removedSelection || (removedURL != nil && selectedFolder?.standardizedFileURL.resolvingSymlinksInPath() == removedURL) {
            selectFolder(nil)
        }
        lastError = selectedFolderError() ?? firstOutstandingFolderError()
    }

    public func selectFolder(_ url: URL?) {
        let standardizedTarget = url?.standardizedFileURL.resolvingSymlinksInPath()
        let currentStandardized = selectedFolder?.standardizedFileURL.resolvingSymlinksInPath()
        
        if let id = folders.first(where: {
            $0.url?.standardizedFileURL.resolvingSymlinksInPath() == standardizedTarget && standardizedTarget != nil
        })?.id {
            defaults.set(id.uuidString, forKey: selectionKey)
        } else {
            defaults.removeObject(forKey: selectionKey)
        }

        // Prevent duplicate selection scopes if already selected
        if let std = standardizedTarget, let cur = currentStandardized, std == cur, !accessedURLs.isEmpty {
            refresh()
            return
        }
        
        for acc in accessedURLs {
            scopeManager.stopAccessing(url: acc)
        }
        accessedURLs.removeAll()
        
        selectedFolder = url
        if let url = url {
            let accessGranted = scopeManager.startAccessing(url: url)
            if accessGranted {
                accessedURLs.append(url)
            }
        }
        refresh()
    }
    
    public func refresh() {
        guard let url = selectedFolder else {
            visibleChildren = []
            lastError = firstOutstandingFolderError()
            return
        }
        
        do {
            let contents = try FileManager.default.contentsOfDirectory(at: url, includingPropertiesForKeys: [.isDirectoryKey, .contentModificationDateKey], options: [.skipsHiddenFiles])
            var nodes: [FileNode] = []
            for child in contents {
                let resourceValues = try? child.resourceValues(forKeys: [.isDirectoryKey, .contentModificationDateKey])
                let isDir = resourceValues?.isDirectory ?? false
                let modDate = resourceValues?.contentModificationDate ?? Date()
                nodes.append(FileNode(url: child, isDirectory: isDir, modificationDate: modDate))
            }
            visibleChildren = nodes.sorted {
                if $0.isDirectory == $1.isDirectory {
                    return $0.name.localizedStandardCompare($1.name) == .orderedAscending
                }
                return $0.isDirectory && !$1.isDirectory
            }
            if let folderID = selectedFolderID() {
                folderReadErrors.removeValue(forKey: folderID)
            }
            lastError = selectedFolderError()
        } catch {
            let message = "Failed to read folder contents: \(error.localizedDescription)"
            if let folderID = selectedFolderID() {
                folderReadErrors[folderID] = message
            }
            lastError = message
            visibleChildren = []
        }
    }
    
    public func open(_ url: URL) {
        NSWorkspace.shared.open(url)
    }
    
    public func reveal(_ url: URL) {
        NSWorkspace.shared.activateFileViewerSelecting([url])
    }
    
    private func loadFolders() {
        guard let data = defaults.data(forKey: defaultsKey) else { return }
        do {
            var decoded = try JSONDecoder().decode([BookmarkedFolder].self, from: data)
            var needsSave = false
            bookmarkRenewalErrors.removeAll()
            folderReadErrors.removeAll()
            for i in 0..<decoded.count {
                var isStale = false
                if let url = try? scopeManager.resolveBookmarkData(decoded[i].bookmarkData, isStale: &isStale) {
                    decoded[i].url = url
                    if isStale {
                        let accessHeld = scopeManager.startAccessing(url: url)
                        if accessHeld {
                            defer { scopeManager.stopAccessing(url: url) }
                            do {
                                let newData = try scopeManager.bookmarkData(for: url)
                                decoded[i].bookmarkData = newData
                                needsSave = true
                            } catch {
                                bookmarkRenewalErrors[decoded[i].id] = "Failed to renew bookmark for \(url.lastPathComponent): \(error.localizedDescription)"
                            }
                        } else {
                            bookmarkRenewalErrors[decoded[i].id] = "Could not access \(url.lastPathComponent) to renew its bookmark."
                        }
                    }
                }
            }
            folders = decoded
            if needsSave { saveFolders() }
            
            let selectedID = defaults.string(forKey: selectionKey).flatMap(UUID.init(uuidString:))
            let restored = folders.first { $0.id == selectedID && $0.url != nil }
            if let url = (restored ?? folders.first { $0.url != nil })?.url {
                selectFolder(url)
            } else {
                defaults.removeObject(forKey: selectionKey)
                lastError = firstOutstandingFolderError()
            }
        } catch {
            lastError = "Failed to load saved folders."
        }
    }
    
    private func saveFolders() {
        if let data = try? JSONEncoder().encode(folders) {
            defaults.set(data, forKey: defaultsKey)
        }
    }

    private func selectedFolderID() -> UUID? {
        guard let selectedFolder else { return nil }
        let target = selectedFolder.standardizedFileURL.resolvingSymlinksInPath()
        return folders.first {
            $0.url?.standardizedFileURL.resolvingSymlinksInPath() == target
        }?.id
    }

    private func selectedFolderError() -> String? {
        if let id = selectedFolderID(), let error = folderReadErrors[id] ?? bookmarkRenewalErrors[id] {
            return error
        }
        return firstOutstandingFolderError()
    }

    private func firstOutstandingFolderError() -> String? {
        folders.first { folderReadErrors[$0.id] != nil || bookmarkRenewalErrors[$0.id] != nil }
            .flatMap { folderReadErrors[$0.id] ?? bookmarkRenewalErrors[$0.id] }
    }
}
