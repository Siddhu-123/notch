    @MainActor
    @Test func concealedPasteboardFilteringAndIntentionalSnippet() async throws {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tempDir) }
        
        let pbName = NSPasteboard.Name(UUID().uuidString)
        let pb = NSPasteboard(name: pbName)
        defer { pb.releaseGlobally() }
        let suiteName = UUID().uuidString
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }
        
        let store = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: defaults, disableTimers: true)
        
        // Concealed, transient, and autogenerated pasteboard contents are excluded.
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.apple.uikit.pasteboard.source.transient"] {
            pb.clearContents()
            pb.setString("secret", forType: .string)
            pb.setString("marked", forType: NSPasteboard.PasteboardType(type))
            store.captureCurrent()
            #expect(store.history.isEmpty)
        }
        
        // Own copy creates snippet and changes pasteboard, but check change-count suppression
        store.copy("A") // Sets ownChangeCount to pb.changeCount
        
        // Direct captureCurrent skips own changeCount
        store.captureCurrent()
        #expect(store.history.isEmpty)
        
        // Later external copy with SAME text "A" is captured because changeCount changes externally
        pb.clearContents()
        pb.setString("A", forType: .string)
        store.captureCurrent()
        #expect(store.history.count == 1)
        #expect(store.history[0].text == "A")
        
        // External copy B
        pb.clearContents()
        pb.setString("B", forType: .string)
        store.captureCurrent()
        #expect(store.history.count == 2)
        #expect(store.history[0].text == "B")
        
        // Intentional snippet A is NOT suppressed anymore and moves to top
        store.addSnippet(text: "A")
        #expect(store.history.count == 2)
        #expect(store.history[0].text == "A")
    }

