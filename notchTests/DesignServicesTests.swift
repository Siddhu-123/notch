    @MainActor
    @Test func clipboardPreferenceRestorationAndTimerLifecycle() async throws {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tempDir) }

        let suiteName = UUID().uuidString
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }

        let pbName = NSPasteboard.Name(UUID().uuidString)
        let pb = NSPasteboard(name: pbName)
        defer { pb.releaseGlobally() }
        let scheduler = MockClipboardTimerScheduler()

        // 1. First run: default false
        var store: ClipboardStore? = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: defaults, timerScheduler: scheduler.schedule)
        #expect(store?.monitoringEnabled == false)
        #expect(scheduler.timers.isEmpty)

        // 2. Enable monitoring and verify repeated call idempotency
        store?.setMonitoringEnabled(true)
        #expect(store?.monitoringEnabled == true)
        #expect(scheduler.scheduledIntervals == [0.5])
        store?.setMonitoringEnabled(true) // idempotent
        #expect(store?.monitoringEnabled == true)
        #expect(scheduler.timers.count == 1)
        #expect(scheduler.timers[0].isValid)

        // Balanced cleanup including deinit
        let firstTimer = scheduler.timers[0]
        let tickAfterDeinit = scheduler.ticks[0]
        weak var weakStore = store
        store = nil // triggers deinit which invalidates timer
        #expect(weakStore == nil)
        #expect(!firstTimer.isValid)
        tickAfterDeinit() // queued callback is harmless after teardown

        // 3. New instance with same defaults restores monitoring preference = true
        let restoredStore = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: defaults, timerScheduler: scheduler.schedule)
        #expect(restoredStore.monitoringEnabled == true)
        #expect(scheduler.timers.count == 2)
        #expect(scheduler.timers[1].isValid)

        // 4. Disable and verify persistence
        restoredStore.setMonitoringEnabled(false)
        #expect(restoredStore.monitoringEnabled == false)
        #expect(!scheduler.timers[1].isValid)
        let disabledStore = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: defaults, timerScheduler: scheduler.schedule)
        #expect(disabledStore.monitoringEnabled == false)
        #expect(scheduler.timers.count == 2)

        // 5. Test stopMonitoringLifecycle preserves opt-in true while explicit disable remains false
        let lifecycleSuite = UUID().uuidString
        let lifecycleDefaults = UserDefaults(suiteName: lifecycleSuite)!
        defer { lifecycleDefaults.removePersistentDomain(forName: lifecycleSuite) }
        let lifecycleScheduler = MockClipboardTimerScheduler()
        var lifecycleStore: ClipboardStore? = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: lifecycleDefaults, timerScheduler: lifecycleScheduler.schedule)
        lifecycleStore?.setMonitoringEnabled(true)
        #expect(lifecycleStore?.monitoringEnabled == true)
        #expect(lifecycleScheduler.timers.count == 1)
        lifecycleStore?.stopMonitoringLifecycle()
        #expect(!lifecycleScheduler.timers[0].isValid)
        // stopping lifecycle timer does not change saved opt-in
        #expect(lifecycleDefaults.bool(forKey: "clipboard.monitoringEnabled") == true)
        #expect(lifecycleStore?.monitoringEnabled == true)
        lifecycleStore = nil
        let recreatedStore = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: lifecycleDefaults, timerScheduler: lifecycleScheduler.schedule)
        #expect(recreatedStore.monitoringEnabled == true)
        #expect(lifecycleScheduler.timers.count == 2)
        #expect(lifecycleScheduler.timers[1].isValid)
        recreatedStore.setMonitoringEnabled(false)
        #expect(recreatedStore.monitoringEnabled == false)
        #expect(!lifecycleScheduler.timers[1].isValid)
        #expect(lifecycleDefaults.bool(forKey: "clipboard.monitoringEnabled") == false)
        let recreatedDisabledStore = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: lifecycleDefaults, timerScheduler: lifecycleScheduler.schedule)
        #expect(recreatedDisabledStore.monitoringEnabled == false)
        #expect(lifecycleScheduler.timers.count == 2)

        // 6. Test disableTimers flag suppresses timer scheduling even when monitoringEnabled is true
        let testTimerSuite = UUID().uuidString
        let testTimerDefaults = UserDefaults(suiteName: testTimerSuite)!
        defer { testTimerDefaults.removePersistentDomain(forName: testTimerSuite) }
        testTimerDefaults.set(true, forKey: "clipboard.monitoringEnabled")
        let disabledScheduler = MockClipboardTimerScheduler()
        let noTimerStore = ClipboardStore(storageDirectory: tempDir, pasteboard: pb, defaults: testTimerDefaults, disableTimers: true, timerScheduler: disabledScheduler.schedule)
        #expect(noTimerStore.monitoringEnabled == true)
        #expect(disabledScheduler.scheduledIntervals.isEmpty)
    }

    @MainActor
    @Test func focusTimerHardeningNonFiniteHugeValuesAndSafeMinMax() async throws {
        let suiteName = UUID().uuidString
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }

        let now = Date(timeIntervalSince1970: 1000)
        let store = FocusTimerStore(defaults: defaults, disableTimers: true, dateProvider: { now })

        // Safe Int.min and negative start
        store.start(minutes: Int.min)
        #expect(store.durationSeconds == 60)
        #expect(store.remainingSeconds == 60)
        #expect(store.formattedRemaining == "01:00")

        store.start(minutes: 0)
        #expect(store.durationSeconds == 60)

        // Safe Int.max start: capped to max 1 year (525600 min)
        store.start(minutes: Int.max)
        #expect(store.durationSeconds == 525600 * 60)
        #expect(store.remainingSeconds == 525600 * 60)
        #expect(!store.formattedRemaining.isEmpty)

        // Restore against NaN / Infinities / huge duration / inconsistent state
        defaults.set(Double.nan, forKey: "focus.durationSeconds")
        defaults.set(Double.infinity, forKey: "focus.remainingSeconds")
        defaults.set(true, forKey: "focus.isRunning")
        defaults.set(false, forKey: "focus.isFinished")
        defaults.set(Double.nan, forKey: "focus.deadline")

        let nanStore = FocusTimerStore(defaults: defaults, disableTimers: true, dateProvider: { now })
        // Zero duration results in idle state
        #expect(nanStore.durationSeconds == 0)
        #expect(nanStore.remainingSeconds == 0)
        #expect(!nanStore.isRunning)
        #expect(!nanStore.isFinished)
        #expect(nanStore.formattedRemaining == "00:00")

        // Inconsistent state where remaining > duration
        defaults.set(100.0, forKey: "focus.durationSeconds")
        defaults.set(500.0, forKey: "focus.remainingSeconds")
        defaults.set(false, forKey: "focus.isRunning")
        defaults.set(false, forKey: "focus.isFinished")
        defaults.removeObject(forKey: "focus.deadline")

        let clampedStore = FocusTimerStore(defaults: defaults, disableTimers: true, dateProvider: { now })
        #expect(clampedStore.durationSeconds == 100.0)
        #expect(clampedStore.remainingSeconds <= clampedStore.durationSeconds)
        #expect(clampedStore.remainingSeconds == 100.0)

        // Huge remaining seconds formatting does not trap Int overflow
        defaults.set(Double.greatestFiniteMagnitude, forKey: "focus.durationSeconds")
        defaults.set(Double.greatestFiniteMagnitude, forKey: "focus.remainingSeconds")
        let hugeStore = FocusTimerStore(defaults: defaults, disableTimers: true, dateProvider: { now })
        #expect(hugeStore.durationSeconds <= FocusTimerStore.maxAllowedDuration)
        #expect(hugeStore.remainingSeconds <= FocusTimerStore.maxAllowedDuration)
        #expect(!hugeStore.formattedRemaining.isEmpty)
    }

    final class MockClipboardTimerScheduler {
        private(set) var scheduledIntervals: [TimeInterval] = []
        private(set) var timers: [Timer] = []
        private(set) var ticks: [() -> Void] = []

        func schedule(_ interval: TimeInterval, _ tick: @escaping () -> Void) -> Timer {
            scheduledIntervals.append(interval)
            ticks.append(tick)
            let timer = Timer(timeInterval: interval, repeats: true) { _ in tick() }
            timers.append(timer)
            return timer
        }
    }

    final class MockSecurityScopeManager: SecurityScopedResourceManaging {
        var startCount = 0
        var stopCount = 0
        var bookmarkCalls = 0
        var resolveCount = 0
        var renewalFails = false
        var isStaleOnResolve = false
        var startGranted = true
        var heldURLs = Set<URL>()
        var events: [String] = []
        var renewedBookmarkData: Data?
        var bookmarkDataMap: [URL: Data] = [:]
        var dataURLMap: [Data: URL] = [:]

        func startAccessing(url: URL) -> Bool {
            startCount += 1
            events.append("start:\(url.path)")
            if startGranted { heldURLs.insert(url) }
            return startGranted
        }

        func stopAccessing(url: URL) {
            stopCount += 1
            events.append("stop:\(url.path)")
            heldURLs.remove(url)
        }

        func bookmarkData(for url: URL) throws -> Data {
            bookmarkCalls += 1
            events.append("bookmark:\(heldURLs.contains(url) ? "held" : "unheld"):\(url.path)")
            if renewalFails { throw NSError(domain: "MockRenewal", code: 1) }
            if let renewedBookmarkData {
                bookmarkDataMap[url] = renewedBookmarkData
                dataURLMap[renewedBookmarkData] = url
                return renewedBookmarkData
            }
            if let data = bookmarkDataMap[url] { return data }
            let data = url.absoluteString.data(using: .utf8)!
            bookmarkDataMap[url] = data
            dataURLMap[data] = url
            return data
        }

        func resolveBookmarkData(_ data: Data, isStale: inout Bool) throws -> URL {
            resolveCount += 1
            events.append("resolve")
            isStale = isStaleOnResolve
            if let url = dataURLMap[data] { return url }
            if let str = String(data: data, encoding: .utf8), let url = URL(string: str) {
                return url
            }
            throw NSError(domain: "MockError", code: -1)
        }
    }

    @MainActor
    @Test func folderBrowserDuplicateURLAndScopeBalanceSeam() async throws {
        let suiteName = UUID().uuidString
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }

        let mock = MockSecurityScopeManager()
        let testDir1 = URL(fileURLWithPath: "/tmp/mock_folder_1")
        let testDir2 = URL(fileURLWithPath: "/tmp/mock_folder_2")

        var store: FolderBrowserStore? = FolderBrowserStore(defaults: defaults, scopeManager: mock)

        // Add first folder
        store?.addFolder(url: testDir1)
        #expect(store?.folders.count == 1)
        #expect(store?.selectedFolder == testDir1)
        #expect(mock.startCount == 1)
        #expect(mock.stopCount == 0)

        // Adding duplicate URL should not duplicate bookmark
        store?.addFolder(url: testDir1)
        #expect(store?.folders.count == 1)
        // Selecting same URL again should not duplicate selection scopes
        store?.selectFolder(testDir1)
        #expect(mock.startCount == 1)

        // Switch to testDir2: stops previous scope and starts new one
        store?.addFolder(url: testDir2)
        #expect(store?.folders.count == 2)
        #expect(store?.selectedFolder == testDir2)
        #expect(mock.startCount == 2)
        #expect(mock.stopCount == 1)

        // Remove active folder: releases scope and clears selectedFolder
        let activeId = store?.folders.first(where: {
            var st = false
            return (try? mock.resolveBookmarkData($0.bookmarkData, isStale: &st)) == testDir2
        })?.id
        #expect(activeId != nil)
        if let activeId = activeId {
            store?.removeFolder(activeId)
        }
        #expect(store?.selectedFolder == nil)
        #expect(mock.startCount == 2)
        #expect(mock.stopCount == 2)

        // Select testDir1 again
        store?.selectFolder(testDir1)
        #expect(mock.startCount == 3)
        #expect(mock.stopCount == 2)

        // Deinit / shutdown balances scopes
        store = nil
        #expect(mock.stopCount == 3)
        #expect(mock.startCount == mock.stopCount)
    }

