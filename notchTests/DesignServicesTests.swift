    @Test func loadEnforcesPinAndTotalLimitsAndNormalizesIds() async throws {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tempDir) }

        var items: [String] = []
        for i in 0..<130 {
            let id = String(format: "00000000-0000-0000-0000-%012d", i + 1)
            items.append(#"{"id": "\#(id)", "text": "pin \#(i)", "createdAt": \#(1000 + i), "isPinned": true}"#)
        }
        // Malformed id, duplicate id with older text, duplicate text, and a non-object element.
        items.append(#"{"id": "not-a-uuid", "text": "badid", "createdAt": 5000, "isPinned": false}"#)
        items.append(#"{"id": "00000000-0000-0000-0000-000000000001", "text": "older dup id", "createdAt": 10, "isPinned": false}"#)
        items.append(#"{"id": "00000000-0000-0000-0000-000000000900", "text": "pin 129", "createdAt": 1, "isPinned": false}"#)
        items.append("42")
        let fileUrl = tempDir.appendingPathComponent("clipboard.json")
        try Data("[\(items.joined(separator: ","))]".utf8).write(to: fileUrl)

        let suiteName = UUID().uuidString
        let defaults = UserDefaults(suiteName: suiteName)!
        defer { defaults.removePersistentDomain(forName: suiteName) }
        let pbName = NSPasteboard.Name(UUID().uuidString)
        let pasteboard = NSPasteboard(name: pbName)
        defer { pasteboard.releaseGlobally() }
        let store = ClipboardStore(storageDirectory: tempDir, pasteboard: pasteboard, defaults: defaults, disableTimers: true)
        #expect(store.history.count <= 100)
        #expect(store.history.filter { $0.isPinned }.count == 50)
        #expect(store.history.contains { $0.text == "badid" })
        #expect(Set(store.history.map(\.id)).count == store.history.count)
        #expect(store.history.filter { $0.text == "pin 129" }.count == 1)
        // Newest 50 pins survive as pins.
        #expect(store.history.filter { $0.isPinned }.allSatisfy { Int($0.text.dropFirst(4))! >= 80 })

        // Normalized state is persisted and stable across reload.
        let reloadPbName = NSPasteboard.Name(UUID().uuidString)
        let reloadPasteboard = NSPasteboard(name: reloadPbName)
        defer { reloadPasteboard.releaseGlobally() }
        let reloaded = ClipboardStore(storageDirectory: tempDir, pasteboard: reloadPasteboard, defaults: defaults, disableTimers: true)
        #expect(reloaded.history.map(\.id) == store.history.map(\.id))
        #expect(reloaded.history.count <= 100)

        // Mutations keep bounds.
        let unpinned = store.history.first { !$0.isPinned }!
        store.togglePin(unpinned.id)
        #expect(!(store.history.first { $0.id == unpinned.id }?.isPinned ?? false))
        for i in 0..<20 { store.addSnippet(text: "new \(i)") }
        #expect(store.history.count <= 100)
        #expect(store.history.filter { $0.isPinned }.count <= 50)
    }

